const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const ts = require('../frontend/node_modules/typescript');
const source = fs.readFileSync(require('node:path').join(__dirname, '../frontend/src/quotePayments.ts'), 'utf8');
const context = { exports: {} };
vm.runInNewContext(ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText, context);
const payments = context.exports.quotePayments;
const example = payments(500000, 300000, 300000);
assert.equal(example.downPayment, 800000);
assert.equal(example.initialPaymentPaidToday, 500000);
assert.equal(5000000 - example.downPayment, 4200000);
assert.equal(example.balance, 0);
assert.equal(example.excess, 0);
assert.equal(payments(500000, 300000, 100000).balance, 200000);
assert.equal(payments(500000, 300000, 400000).excess, 100000);
assert.equal(payments(500000, 0).downPayment, 500000);
assert.equal(payments(0, 300000, 300000).downPayment, 300000);
assert.equal(payments(0, 0).downPayment, 0);
assert.equal(payments(100000, 500000, 500000).balance, 0);
console.log('OK: inicial + extra, saldo financiado, plan exacto, faltante, exceso y valores cero.');
const bundle = context.exports.isQuoteBundle;
const products = [{ id: 'a', category: 'Electrodomesticos' }, { id: 'b', category: 'Electrodomesticos' }, { id: 'm', category: 'Motos' }];
const categories = [{ name: 'Electrodomesticos', active: true, quoteAsBundle: true }, { name: 'Motos', active: true, quoteAsBundle: false }];
assert.equal(bundle([{ productId: 'a' }], products, categories), true);
assert.equal(bundle([{ productId: 'a' }, { productId: 'b' }], products, categories), true);
assert.equal(bundle([{ productId: 'a' }, { productId: 'm' }], products, categories), false);
assert.equal(bundle([{ productId: 'm' }], products, categories), false);
assert.equal(bundle([{ productId: 'a' }, { productId: '' }], products, categories), false);
assert.equal(bundle([], products, categories), false);
assert.equal(bundle([{ productId: 'a' }], products, []), false);
console.log('OK: paquete desde un articulo, categorias mixtas e individuales permanecen comparativas.');
assert.equal(context.exports.quoteTermLimit('Electrodomésticos'), 24);
assert.equal(context.exports.quoteTermLimit('ELECTRODOMESTICOS'), 24);
assert.equal(context.exports.quoteTermLimit('Motos'), 40);
assert.equal(context.exports.quoteTermLimit(), 40);
assert.equal(context.exports.quoteCustomerName('María José Muñoz'), 'MARÍA JOSÉ MUÑOZ');
assert.equal(context.exports.currencyInputValue(1500000), '1.500.000');
assert.equal(context.exports.currencyInputValue(0), '');
assert.equal(context.exports.currencyInputValue(undefined), '');
console.log('OK: limites 40/24, nombres con tildes en mayusculas, miles y cero vacio.');
const changeTerms = context.exports.updateQuoteTerms;
assert.equal(JSON.stringify(changeTerms([24], 12, 24)), '[12,24]');
assert.equal(JSON.stringify(changeTerms([12,24], 18, 24)), '[12,18,24]');
assert.equal(JSON.stringify(changeTerms([12,18,24], 18, 24)), '[12,24]');
assert.equal(JSON.stringify(changeTerms([12,24], 24, 24, false)), '[12,24]');
assert.equal(JSON.stringify(changeTerms([24], 36, 24)), '[24]');
assert.equal(JSON.stringify(changeTerms([24], 1.5, 24)), '[24]');
assert.equal(JSON.stringify(changeTerms([24], 0, 24)), '[24]');
assert.equal(JSON.stringify(changeTerms([24], 40, 40)), '[24,40]');
assert.equal(JSON.stringify(changeTerms([24], 24, 24)), '[]');
console.log('OK: seleccion multiple intuitiva, quitar, agregar sin duplicar y respetar maximos.');
